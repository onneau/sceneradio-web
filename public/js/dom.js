export function icon(name, size = 24) {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'currentColor');
  svg.setAttribute('aria-hidden', 'true');
  const path = document.createElementNS(SVG_NS, 'path');
  path.setAttribute('d', ICONS[name] || '');
  svg.append(path);
  return svg;
}

let toastTimer = 0;
export function toast(message, { bad = false, ms = 4500 } = {}) {
  document.querySelector('.toast')?.remove();
  const el = h('div', { class: `toast${bad ? ' bad' : ''}`, role: 'status' }, message);
  document.body.append(el);
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => el.remove(), ms);
}


export function initials(name) {
  const words = String(name).replace(/[^\p{L}\p{N} ]/gu, '').split(/\s+/).filter(Boolean);
  const letters = words.length > 1 ? words[0][0] + words[1][0] : (words[0] || '?').slice(0, 2);
  return letters.toUpperCase();
}

/** Een logo met een nette vervanger als er geen is of het niet laadt. */
export function logoImage(station, className = 'logo', { small = false } = {}) {
  const fallback = () => h('div', { class: `fallback-logo${small ? ' small' : ''}` }, initials(station.name));
  if (!station.logo) return fallback();
  const v = station.logo.v ? `?v=${encodeURIComponent(station.logo.v)}` : '';
  const img = h('img', { class: className, src: `/api/logo/${station.id}${v}`, alt: '', loading: 'lazy', decoding: 'async' });
  img.addEventListener('error', () => img.replaceWith(fallback()), { once: true });
  return img;
}
